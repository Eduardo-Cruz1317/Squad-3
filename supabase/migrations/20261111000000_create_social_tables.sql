-- Guarda de ambiente: a unicidade do nome ignora maiúsculas/minúsculas via LOWER().
-- Em bancos com locale C/POSIX, LOWER() não trata letras acentuadas e a unicidade
-- ficaria silenciosamente mais fraca. Falha cedo em vez de falhar em produção.
DO $$
BEGIN
  IF lower('Á') <> 'á' THEN
    RAISE EXCEPTION 'LOWER() nao trata letras acentuadas neste banco (locale C/POSIX). Use um banco com encoding UTF8 e locale como en_US.UTF-8.';
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.categories (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  CONSTRAINT categories_name_key UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS public.guilds (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  name        TEXT NOT NULL,
  category_id BIGINT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT guilds_category_id_fkey
    FOREIGN KEY (category_id) REFERENCES public.categories (id)
);

-- Unicidade do nome sem diferenciar caixa ("Física Básica" = "física básica").
-- É a garantia final contra duas criações simultâneas.
CREATE UNIQUE INDEX IF NOT EXISTS guilds_name_unique_ci ON public.guilds (LOWER(name));
CREATE INDEX IF NOT EXISTS guilds_category_id_idx ON public.guilds (category_id);

CREATE TABLE IF NOT EXISTS public.guild_memberships (
  guild_id  BIGINT NOT NULL,
  user_id   BIGINT NOT NULL,
  role      TEXT   NOT NULL,
  joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT guild_memberships_pkey PRIMARY KEY (guild_id, user_id),
  CONSTRAINT guild_memberships_guild_id_fkey
    FOREIGN KEY (guild_id) REFERENCES public.guilds (id) ON DELETE CASCADE,
  CONSTRAINT guild_memberships_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE,
  -- Domínio de valores da coluna (integridade). Não define QUEM recebe cada papel.
  CONSTRAINT guild_memberships_role_check CHECK (role IN ('admin', 'member'))
);

CREATE INDEX IF NOT EXISTS guild_memberships_user_id_idx ON public.guild_memberships (user_id);

-- Segurança do Supabase: acesso pela connection string privilegiada da aplicação
-- não é afetado por RLS; as chaves anon/authenticated não recebem acesso à Data API.
ALTER TABLE public.categories        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.guilds            ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.guild_memberships ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.categories, public.guilds, public.guild_memberships FROM anon, authenticated;
